"""Cut the theme's webfonts. Run with: uv run scripts/build-fonts.py

The common CJK subset is GB2312 level-1, punctuation, and characters already
used in the content. Other glyphs ship as Unicode-range slices, so a new post
can use the fonts as they are. The script does not install fonts on the system.
"""
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path
import tempfile
import os
import subprocess
import logging

import py7zr
from fontTools import subset
from fontTools.ttLib import TTFont

logging.getLogger("fontTools").setLevel(logging.ERROR)
ROOT = Path(__file__).resolve().parents[1]
THEME = ROOT
CACHE = Path(os.environ.get("CHIPAPER_FONT_CACHE", str(Path(tempfile.gettempdir()) / "chipaper-fonts")))
OUTPUT = THEME / "static/fonts"
SARASA_VERSION = "1.0.43"


def download(url, destination):
    destination.parent.mkdir(parents=True, exist_ok=True)
    if not destination.exists():
        subprocess.run(["curl", "--fail", "--location", "--silent", "--show-error", "--retry", "2", url, "--output", str(destination)], check=True)


def unicode_range(points):
    groups = []
    start = previous = points[0]
    for point in points[1:]:
        if point != previous + 1:
            groups.append(f"U+{start:X}" if start == previous else f"U+{start:X}-{previous:X}")
            start = point
        previous = point
    groups.append(f"U+{start:X}" if start == previous else f"U+{start:X}-{previous:X}")
    return ",".join(groups)


def build_sarasa(job):
    source, weight, common = job
    source = Path(source)
    available = set(TTFont(source).getBestCmap())
    # Latin comes from Google Sans Code. Keep CJK, full-width punctuation,
    # and symbols from Sarasa; let the OS handle other scripts when needed.
    cjk = {p for p in available if p >= 0x2E80 or 0x2000 <= p <= 0x206F}
    primary = sorted(cjk & common)
    remaining = cjk - common
    chunks = [("common", primary)]
    for bucket in sorted({point // 1024 for point in remaining}):
        points = sorted(p for p in remaining if p // 1024 == bucket)
        chunks.append((f"{bucket:03x}", points))
    rules = []
    for name, points in chunks:
        font = TTFont(source)
        options = subset.Options()
        options.flavor = "woff2"
        options.layout_features = ["*"]
        options.recalc_timestamp = False
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=points)
        sub.subset(font)
        filename = f"sarasa-sc-{weight}-{name}.woff2"
        font.flavor = "woff2"
        font.save(OUTPUT / filename)
        rules.append(
            "@font-face{font-family:'Sarasa Mono SC';font-style:normal;"
            f"font-weight:{weight};font-display:swap;"
            f"src:url('../fonts/{filename}') format('woff2');"
            f"unicode-range:{unicode_range(points)};}}"
        )
    return rules


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    CACHE.mkdir(parents=True, exist_ok=True)
    archive = CACHE / "sarasa.7z"
    download(
        f"https://github.com/be5invis/Sarasa-Gothic/releases/download/v{SARASA_VERSION}/SarasaMonoSC-TTF-Unhinted-{SARASA_VERSION}.7z",
        archive,
    )
    with py7zr.SevenZipFile(archive) as seven:
        names = seven.getnames()
        regular = next(n for n in names if n.lower().endswith("-regular.ttf"))
        bold = next(n for n in names if n.lower().endswith("-bold.ttf"))
        if not all((CACHE / n).exists() for n in (regular, bold)):
            seven.extract(path=CACHE, targets=[regular, bold])
    google = CACHE / "google-sans-code.ttf"
    download("https://raw.githubusercontent.com/google/fonts/main/ofl/googlesanscode/GoogleSansCode%5Bwght%5D.ttf", google)
    font = TTFont(google)
    font.flavor = "woff2"
    font.save(OUTPUT / "google-sans-code.woff2")
    common = set(range(0x2000, 0x2070)) | set(range(0x3000, 0x3040)) | set(range(0xFF00, 0xFFF0))
    for high in range(0xB0, 0xD8):
        for low in range(0xA1, 0xFF):
            try:
                common.update(map(ord, bytes([high, low]).decode("gb2312")))
            except UnicodeDecodeError:
                pass
    for directory in (ROOT / "exampleSite/content", THEME / "layouts"):
        for item in directory.rglob("*"):
            if item.is_file():
                common.update(map(ord, item.read_text(encoding="utf-8")))
    jobs = [(str(CACHE / regular), 400, common), (str(CACHE / bold), 700, common)]
    with ProcessPoolExecutor(max_workers=2) as pool:
        results = list(pool.map(build_sarasa, jobs))
    rules = ["/* Generated by scripts/build-fonts.py. See font licenses. */",
             "@font-face{font-family:'Google Sans Code';font-style:normal;font-weight:300 800;font-display:swap;src:url('../fonts/google-sans-code.woff2') format('woff2');}"]
    for result in results:
        rules.extend(result)
    (THEME / "assets/css/fonts.css").write_text("\n".join(rules) + "\n")
    download("https://raw.githubusercontent.com/be5invis/Sarasa-Gothic/main/LICENSE", THEME / "licenses/Sarasa-Gothic-OFL.txt")
    download("https://raw.githubusercontent.com/google/fonts/main/ofl/googlesanscode/OFL.txt", THEME / "licenses/Google-Sans-Code-OFL.txt")
    total = sum(item.stat().st_size for item in OUTPUT.glob("*.woff2"))
    print(f"Built {len(list(OUTPUT.glob('*.woff2')))} font files ({total / 1024 / 1024:.2f} MiB total).")
    for item in sorted(OUTPUT.glob("*common.woff2")):
        print(f"  {item.name}: {item.stat().st_size / 1024:.0f} KiB")


if __name__ == "__main__":
    main()
